ObjC.import('Foundation');
// Подключение группы согласования. Владелица 17.09 захотела подключить её
// своими руками. Два требования, которые нельзя нарушить:
// 1. Токен бота идёт в Vault прямо из браузера — через наш сервер он не
//    проходит и назад не читается (то же правило, что у ключей провайдеров).
// 2. purpose обязателен: у клиента ДВА телеграма — группа согласования и
//    канал публикации. Без него второй вытесняет первый, и материал уходит
//    подписчикам вместо проверки (миграция 007 контент-машины).
function readFile(p){return $.NSString.stringWithContentsOfFileEncodingError($(p),$.NSUTF8StringEncoding,null).js;}
var ROOT=$.NSFileManager.defaultManager.currentDirectoryPath.js;
var SRC=readFile(ROOT+'/app.jsx');
console.log('tests/approval-channel.test.js');
var провалов=0;
function ок(имя,усл,что){ if(усл) console.log('  ok   '+имя); else { провалов++; console.log('  FAIL '+имя+(что?': '+что:'')); } }

var i=SRC.indexOf('const saveApprovalChannel');
var блок=SRC.slice(i, i+2200);
ок('форма зовёт set_approval_channel', /rpc\/set_approval_channel/.test(блок), 'нет');
ок('назначение канала указано явно', /p_purpose: 'approval'/.test(блок), 'нет');
ок('вид площадки указан', /p_kind: 'telegram'/.test(блок), 'нет');
ок('токен уходит прямо в базу, мимо наших функций',
   /fetch\(A\.SUPABASE_URL \+ '\/rest\/v1\/rpc\/set_approval_channel'/.test(блок), 'идёт через api/*');
ок('в теле нет нашего сервера', !/\/api\//.test(блок), 'есть обращение к api');
ок('после сохранения токен стирается из формы', /setChToken\(''\)/.test(блок), 'остался в состоянии');
ок('ошибка про отсутствующую миграцию человеческая',
   /Хранилище каналов в базе ещё не заведено/.test(блок), 'нет');

var j=SRC.indexOf('const checkApprovalChannel');
var проверка=SRC.slice(j, j+3000);
// Проверка идёт через функцию базы: она сверяет доступ, отказывает без
// подключённого канала и склеивает повторные нажатия в одно задание — пять
// сообщений в рабочую группу выглядели бы как сломавшийся сервис
// (контент-машина, миграция 009).
ок('проверка идёт через функцию базы', /rpc\/queue_channel_check/.test(проверка), 'нет');
ок('передан вид площадки и назначение',
   /p_kind: 'telegram'/.test(проверка) && /p_purpose: 'approval'/.test(проверка), 'нет');
// Миграции применяет владелица — до этого функции в базе нет, и кнопка
// обязана работать прежним путём, а не падать.
ок('есть запасной путь без миграции', /kind: 'verify_channel'/.test(проверка), 'нет');
ок('запасной путь включается только при отсутствии функции',
   /does not exist\|schema cache/.test(проверка), 'включается всегда');
ок('человеку сказано, где смотреть результат',
   /загляните в группу/.test(проверка), 'нет');

// Токен нигде не печатается и не хранится дальше формы.
ок('токен не уходит в console', !/console\.[a-z]+\([^)]*chToken/.test(SRC), 'печатается');
ок('токен не пишется в бриф или проект', !/chToken[^)]{0,40}(setBrief|sv\()/.test(SRC), 'сохраняется');

// Разница назначений объяснена человеку, а не только в коде.
ок('в форме сказано, что это не канал подписчиков',
   /Это не канал\s*\n?\s*для подписчиков|Это не канал для подписчиков/.test(SRC), 'нет');

// Форма нужна ВСЕМ клиентам, а не только тем, кто на своих ключах: вопрос про
// ключ прячется на подписке потому, что ключа там нет, а согласование есть у
// каждого. На подписке своего бота заводить не надо — в группу добавляют
// нашего (контент-машина, миграция 008).
ок('карточка согласования — отдельная, не внутри блока ключей',
   /const картаСогласования = \(/.test(SRC), 'нет');
ок('показывается любому клиенту', /\{clientIdFromUrl && \(\s*\n\s*<div className="card">\s*\n\s*<p[^>]*>Группа согласования/.test(SRC), 'скрыта тарифом');
ок('на подписке просим бота платформы', /p_bot: тарифРазработчика \? 'own' : 'platform'/.test(SRC), 'нет');
ок('на подписке токен не отправляем',
   /\.\.\.\(тарифРазработчика \? \{ p_token: chToken\.trim\(\) \} : \{\}\)/.test(SRC), 'шлём всегда');
ок('поле токена показывается только на своих ключах',
   /\{тарифРазработчика && \(\s*\n\s*<input type="password"/.test(SRC), 'видно всем');
ок('кнопка не требует токен на подписке',
   /disabled=\{!chAddr\.trim\(\)\|\|\(тарифРазработчика&&!chToken\.trim\(\)\)\|\|chBusy\}/.test(SRC), 'требует');
ок('подписчику сказано добавить нашего бота',
   /добавьте в группу нашего и дайте ему право/.test(SRC), 'нет');

console.log(провалов ? ('ПРОВАЛОВ: '+провалов) : 'группа согласования подключается безопасно');
