function readFile(p){return $.NSString.stringWithContentsOfFileEncodingError($(p),$.NSUTF8StringEncoding,null).js;}
var ROOT=$.NSFileManager.defaultManager.currentDirectoryPath.js;
var SRC=readFile(ROOT+'/app.jsx');
function взять(n){var i=SRC.indexOf('async function '+n+'('); if(i<0) i=SRC.indexOf('function '+n+'(');
 if(i<0) throw new Error('нет '+n);
 var d=0; for(var k=SRC.indexOf('{',i);k<SRC.length;k++){if(SRC[k]==='{')d++;else if(SRC[k]==='}'){d--;if(!d)return SRC.slice(i,k+1);}}}
console.log('tests/audience-profile.test.js');
var провалов=0;
function ок(имя,усл,что){ if(усл) console.log('  ok   '+имя); else { провалов++; console.log('  FAIL '+имя+(что?': '+что:'')); } }

// Схема портрета — то, ради чего делается лишний вызов модели.
var i=SRC.indexOf('const СХЕМА_ПРОФИЛЯ');
eval(SRC.slice(i, SRC.indexOf('\nasync function профильАудитории', i)).replace('const ','var '));
var поля=СХЕМА_ПРОФИЛЯ.properties.портреты.items;
['сегмент','роль','контекст_жизни','интересы','что_читают','поисковые_фразы','где_искать_каналы']
  .forEach(function(п){ ок('в портрете есть «'+п+'»', поля.required.indexOf(п)>=0, 'нет'); });
ок('интересы — список', поля.properties.интересы.type, 'array');
ок('поисковые фразы — список', поля.properties.поисковые_фразы.type, 'array');
ок('фразы просят не про продукт, а про жизнь',
   /не про наш продукт, а про его жизнь/i.test(поля.properties.поисковые_фразы.description), 'нет правила');

// Запросы поиска строятся из портрета, а не из имени сегмента.
globalThis.PROXY='https://p.test';
