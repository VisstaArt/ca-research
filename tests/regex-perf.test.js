ObjC.import('Foundation');
// Сторож скорости разбора страниц.
//
// 17.09 прогон M4 замирал на замерах каналов: строка вида
//   /([\d\s.,]+ ... )\s*(?:subscribers|подписчик)/
// перед обязательным словом перебирает все длины подряд, и время растёт
// КВАДРАТИЧНО от размера страницы — 16 КБ считались 22 секунды, а страница
// VK или YouTube весит сотни килобайт. Вкладка стояла намертво, отчёт не
// досчитывался, деньги за прогон уходили впустую.
//
// Тест берёт КАЖДУЮ регулярку, которую код применяет к целой странице, и
// прогоняет её на 200 КБ текста, похожего на минифицированную страницу.
// Дольше секунды — значит регулярка снова с перебором.
function readFile(p){return $.NSString.stringWithContentsOfFileEncodingError($(p),$.NSUTF8StringEncoding,null).js;}
var ROOT=$.NSFileManager.defaultManager.currentDirectoryPath.js;
var SRC=readFile(ROOT+'/app.jsx');
console.log('tests/regex-perf.test.js');
var провалов=0;
function ок(имя,усл,что){ if(усл) console.log('  ok   '+имя); else { провалов++; console.log('  FAIL '+имя+(что?': '+что:'')); } }

// Текст, на котором взрывается перебор: длинные цепочки цифр, запятых и
// пробелов — ровно то, из чего состоит встроенный в страницу JSON.
var кусок='1,2,3,4,5 999 000, 12.5K ';
var страница='';
while(страница.length<200000) страница+=кусок;

// Все регулярки исходника, применённые к переменной html.
var найдено=[], ре=/html\.(?:match|replace|split)\((\/(?:\\.|\[(?:\\.|[^\]])*\]|[^\/\\\n])+\/[gimsuy]*)\)/g, м;
while((м=ре.exec(SRC))) if(найдено.indexOf(м[1])<0) найдено.push(м[1]);
ок('регулярки по странице найдены', найдено.length>=5, 'нашли '+найдено.length);

найдено.forEach(function(исх){
  var r; try { r=eval('('+исх+')'); } catch(e){ ок('разбор '+исх, false, e.message); return; }
  var t0=Date.now();
  try { if(r.global) { r.lastIndex=0; while(r.exec(страница)); } else страница.match(r); } catch(e){}
  var мс=Date.now()-t0;
  ок(исх.slice(0,60)+' — '+мс+' мс', мс<1000, 'перебор: '+мс+' мс на 200 КБ');
});

// Отдельно — сам поиск подписчиков в замерКанала: он должен остаться линейным.
ок('нет старой регулярки подписчиков',
   SRC.indexOf('[\\d\\s.,]+[KM')<0,
   'вернулась регулярка с перебором перед словом subscribers');

// Новый поиск подписчиков: слово ищем линейно, разбираем окно перед ним.
// Проверяем и скорость, и что число всё ещё находится.
ок('код ищет слово, а не перебирает числа перед ним',
   SRC.indexOf('/subscribers|members|подписчик|участник/gi')>0
   && SRC.indexOf('const слово = этоМатериал')>0,
   'блок поиска подписчиков переписан — проверьте скорость вручную');
(function(){
  var стр=страница+'<span class="count">83.2K</span> <span>subscribers</span>';
  var t0=Date.now(), подписчики=null;
  var слово=/subscribers|members|подписчик|участник/gi, к, найдено=0;
  while(подписчики==null && (к=слово.exec(стр)) && найдено<20){
    найдено++;
    var окно=стр.slice(Math.max(0,к.index-48),к.index).replace(/<[^>]*>/g,' ');
    var ч=/([0-9][0-9\s.,\u00A0]{0,15})\s*(K|M|К|М|тыс\.?|млн\.?)?\s*$/i.exec(окно);
    if(ч) подписчики=ч[1]+(ч[2]||'');
  }
  var мс=Date.now()-t0;
  ок('поиск подписчиков на 200 КБ — '+мс+' мс', мс<1000, 'снова перебор');
  ок('подписчики найдены: '+подписчики, /83[.,]2\s*K/i.test(String(подписчики)), 'нашли '+подписчики);
})();

console.log(провалов?('  '+провалов+' провал(ов)'):'  всё зелено');
if(провалов) $.NSException.exceptionWithNameReasonUserInfo($('tests'),$('regex-perf'),$()).raise;
