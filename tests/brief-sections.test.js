ObjC.import('Foundation');
// Бриф разложен по частям, а набор модулей вынесен из брифа.
// 18.09 владелица: «модули лежат так далеко — в бриф перейди, там измени, и
// только потом они появятся. Бриф это данные о проекте, а модули — нет.
// И сам бриф разделить, чтобы не перечитывать простыни».
function readFile(p){return $.NSString.stringWithContentsOfFileEncodingError($(p),$.NSUTF8StringEncoding,null).js;}
var ROOT=$.NSFileManager.defaultManager.currentDirectoryPath.js;
var SRC=readFile(ROOT+'/app.jsx');
console.log('tests/brief-sections.test.js');
var провалов=0;
function ок(имя,усл,что){ if(усл) console.log('  ok   '+имя); else { провалов++; console.log('  FAIL '+имя+(что?': '+что:'')); } }

// ── Набор модулей правится на экране прогона ────────────────────────────────
ок('панель набора открывается на месте',
   /const \[выборМодулей, setВыборМодулей\]/.test(SRC) && /\{выборМодулей && !isRun && \(/.test(SRC),
   'нет панели выбора модулей на экране прогона');
ок('кнопка больше не уводит в бриф',
   /onClick=\{открытьВыборМодулей\}/.test(SRC)
   && (SRC.match(/onClick=\{открытьВыборМодулей\}/g)||[]).length>=2,
   'кнопки «Добавить модули» снова зовут setSc(\'form\')');
ок('набор сохраняется прямо оттуда',
   /const сохранитьНабор = React\.useCallback/.test(SRC) && /onClick=\{сохранитьНабор\}/.test(SRC),
   'выбор некуда сохранить');
ок('«Отмена» возвращает как было',
   /const наборДоПравки = React\.useRef/.test(SRC) && /onClick=\{отменитьВыборМодулей\}/.test(SRC),
   'отмена оставляет изменённый набор');

// ── Бриф разложен по частям ────────────────────────────────────────────────
ок('есть компонент части', /function Разд\(\{ имя, подпись, children \}\)/.test(SRC), 'нет компонента');
ок('части сворачиваются', /const \[открыт, setОткрыт\] = React\.useState\(true\)/.test(SRC),
   'часть нельзя свернуть — простыня осталась простынёй');
var части = (SRC.match(/<Разд имя="([^"]+)"/g)||[]).map(function(x){ return x.slice(11,-1); });
ок('частей три: ' + части.join(' · '), части.length === 3, 'нашли ' + части.length);
['О компании и продукте','Где вы уже есть','Оформление'].forEach(function(имя){
  ок('часть «'+имя+'» на месте', части.indexOf(имя)>=0, 'нет такой части');
});
ок('все части закрыты', (SRC.match(/<\/Разд>/g)||[]).length === части.length,
   'число открытий и закрытий не сходится — вёрстка поедет');

// Данные оформления лежат ИМЕННО в своей части, а не вперемешку.
var i=SRC.indexOf('<Разд имя="Оформление"'), j=SRC.indexOf('</Разд>', i);
var оформление=SRC.slice(i,j);
['brandColors','brandFonts','brandLogo'].forEach(function(поле){
  ок('в «Оформлении» есть '+поле, оформление.indexOf('brief.'+поле)>0, 'поле не в своей части');
});
ок('в «Оформлении» нет чужих полей',
   оформление.indexOf('brief.price')<0 && оформление.indexOf('brief.audience')<0,
   'в часть оформления затесались данные о компании');

console.log(провалов?('ПРОВАЛОВ: '+провалов):'  бриф разложен, модули вынесены');
if(провалов) $.NSException.exceptionWithNameReasonUserInfo($('tests'),$('brief-sections'),$()).raise;
