ObjC.import('Foundation');
// Сбой поиска ≠ «ничего не нашлось».
// 18.09 владелица дважды заплатила за прогон M4A и получила три пустых блока
// с советом «уточните бриф». На деле поиск не отработал ни разу: сводка сбора
// показала «0 страниц из поиска». callSearch глотал любую ошибку и возвращал
// пустой список — отличить «поиск сломан» от «в нише пусто» было нечем.
function readFile(p){return $.NSString.stringWithContentsOfFileEncodingError($(p),$.NSUTF8StringEncoding,null).js;}
var ROOT=$.NSFileManager.defaultManager.currentDirectoryPath.js;
var SRC=readFile(ROOT+'/app.jsx');
console.log('tests/search-failure.test.js');
var провалов=0;
function ок(имя,усл,что){ if(усл) console.log('  ok   '+имя); else { провалов++; console.log('  FAIL '+имя+(что?': '+что:'')); } }

var i=SRC.indexOf('async function callSearch');
var тело=SRC.slice(i, SRC.indexOf('\n}\n', i));
ок('неудачи поиска считаются', /сбойПоиска\.неудач\+\+/.test(тело), 'ошибка снова глотается молча');
ок('код ответа запоминается', /сбойПоиска\.код = res\.status/.test(тело), 'нет кода ответа');
ок('причина читается из тела ответа', /д\.error && д\.error\.message/.test(тело), 'причина не разбирается');
ок('обрыв связи тоже причина', /связь оборвалась/.test(тело), 'catch снова молчит');
ок('счётчик свой у каждого модуля',
   /сброситьСбойПоиска\(\);/.test(SRC) && /searchCallCount = 0;.*\n.*сброситьСбойПоиска/.test(SRC),
   'причина протечёт из прошлого модуля');

// Ранний выход: не платить за модель, когда сырья взяться неоткуда.
var j=SRC.indexOf('async function gatherEvidence');
var сбор=SRC.slice(j, SRC.indexOf('\n}\n', j));
ок('серия ошибок обрывает сбор', /подрядПусто >= 5\) break/.test(сбор),
   'прогон снова сделает все запросы впустую');

// Отчёт обязан назвать причину, а не советовать «уточните бриф».
ок('есть плашка про сбой поиска', /function плашкаСбояПоиска\(сб\)/.test(SRC), 'нет плашки');
ок('плашка стоит в обеих сводках',
   (SRC.match(/\+ плашкаСбояПоиска\(сб\)/g)||[]).length >= 2, 'плашка не выводится');
ок('плашка отличает исчерпанный лимит',
   /лимит поисковых запросов/.test(SRC) && /Ключ поиска не принят/.test(SRC),
   'причины не разделены — человек не поймёт, что чинить');
ок('прямо сказано, что бриф ни при чём',
   /следствие ЭТОГО, а не того, что в нише ничего нет/.test(SRC),
   'пустые разделы снова спишут на нишу');
ок('причина доезжает до сводок',
   (SRC.match(/сбойПоиска: \{ \.\.\.сбойПоиска \}/g)||[]).length >= 2,
   'сводка сбора не получает причину');

console.log(провалов?('ПРОВАЛОВ: '+провалов):'  сбой поиска виден, а не выдаётся за пустую нишу');
if(провалов) $.NSException.exceptionWithNameReasonUserInfo($('tests'),$('search-failure'),$()).raise;
