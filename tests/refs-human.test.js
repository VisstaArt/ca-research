check('адрес не переведён', адрес.indexOf('href="https://x.ru/type/name/source"') >= 0);
check('видимая часть адреса цела', адрес.indexOf('x.ru/type/name/source') >= 0);


// Шкала уверенности объясняется под ТОЙ таблицей, где стоит её колонка:
// владелица 15.09 искала её сперва под источниками, потом поняла, что оценка
// относится к нишам. Сноска ставится сама, один раз на модуль.
var сУверенностью = ['## BLOCK 04_2 — Приоритет ниш',
 '| Ниша | Спрос (1-5) | ИТОГО | Уверенность (1-5) | Вердикт |',
 '|---|---|---|---|---|',
 '| Магазины | 5 | 19 | 4 | Идём |',
 '', '## BLOCK 04 — Сегменты аудитории',
 '| Сегмент | Доля | Confidence |', '|---|---|---|', '| Владельцы | 30% | 3 |'].join('\n');
var разметка = renderResearchHTML(сУверенностью, {}).html;
check('шкала показана у таблицы с колонкой', разметка.indexOf('confleg') >= 0);
check('цифры в шкале выделены', /<b>5<\/b> — три и более независимых свежих источника/.test(разметка));
check('шкала стоит у каждой таблицы со своей колонкой',
  (разметка.match(/class="note confleg"/g)||[]).length === 2);
// Матрицы ниш в модуле нет — шкала встаёт под первой таблицей с колонкой,
// иначе цифры в столбце остались бы без объяснения.
var толькоСегменты = ['## BLOCK 04 — Сегменты аудитории',
 '| Сегмент | Доля | Confidence |','|---|---|---|','| Владельцы | 30% | 3 |'].join('\n');
check('без матрицы ниш шкала показана у сегментов',
  renderResearchHTML(толькоСегменты, {}).html.indexOf('confleg') >= 0);

check('без колонки уверенности шкалы нет',
  renderResearchHTML('## BLOCK 04 — Сегменты\n| Сегмент |\n|---|\n| Владельцы |', {}).html.indexOf('confleg') < 0);


// Буквы достатка объясняются там же, где стоят: владелица 15.09 спросила,
// что значат H и M.
