ObjC.import('Foundation');
// Воронка источников и отбор ЗАМЕРОМ.
// 18.09 владелица: «130 страниц в отчёте смотрится смешно; надо показать,
// сколько вообще было на начальном этапе и из скольких тысяч отобрано».
// И главное: отбирать должен замер, а не то, что модель заметила.
function readFile(p){return $.NSString.stringWithContentsOfFileEncodingError($(p),$.NSUTF8StringEncoding,null).js;}
var ROOT=$.NSFileManager.defaultManager.currentDirectoryPath.js;
var SRC=readFile(ROOT+'/app.jsx');
console.log('tests/funnel-sources.test.js');
var провалов=0;
function ок(имя,усл,что){ if(усл) console.log('  ok   '+имя); else { провалов++; console.log('  FAIL '+имя+(что?': '+что:'')); } }

// Сбор считает, что пришло и что отсеялось.
ок('сбор ведёт счёт ступеней',
   /out\.воронка = \{/.test(SRC) && /ссылокВыдачи: all\.length/.test(SRC)
   && /срезаноДоменом/.test(SRC) && /невлезло/.test(SRC),
   'нечего показать в воронке');
ок('отсев по домену и по месту больше не молчит',
   /\{ срезаноДоменом\+\+; continue; \}/.test(SRC)
   && /\{ невлезло\+\+; continue; \}/.test(SRC),
   'потери материала не считаются');

// Массовый замер каналов.
ок('есть массовый замер найденных каналов',
   /async function замеритьВсеКанальныеСсылки\(выдержки, максимум, бюджетМс, конкуренты\)/.test(SRC),
   'отбор снова делает модель, а не числа');
ок('замеряются только те площадки, что отдают числа',
   /const ЗАМЕРЯЕМЫЕ = /.test(SRC), 'будем ломиться на сайты без счётчиков');
ок('один канал замеряется один раз',
   /if \(виден\.has\(ключ\)\) continue/.test(SRC), 'потратим время на дубли');
ок('грузим пачками, а не по одному',
   /const ПАЧКА = 5;/.test(SRC) && /await Promise\.all\(пачка\.map/.test(SRC),
   'четыреста загрузок по очереди растянут прогон на полчаса');
ок('есть срок и остановка',
   /Date\.now\(\) > срок \|\| прогонОстановлен\(\)/.test(SRC),
   'замер не прервать');
ок('отбор по охвату',
   /готово\.sort\(\(а, б\) => б\.охватЧислом - а\.охватЧислом\)/.test(SRC),
   'в разбор пойдут случайные каналы');

// Замеренные каналы доезжают до модели с числами.
ок('каналы уходят в проходы отдельным списком',
   /КАНАЛЫ, КОТОРЫЕ МЫ УЖЕ ЗАМЕРИЛИ САМИ/.test(SRC),
   'модель не увидит наших чисел');
ок('числа запрещено переписывать',
   /ЧИСЛА ОТСЮДА ПЕРЕНОСИ КАК ЕСТЬ/.test(SRC), 'модель округлит по-своему');
ок('замеры сохраняются для повтора',
   /каналыЗамеренные: замеренныеКаналы\.slice\(0, 120\)/.test(SRC),
   'восемь минут загрузок будут повторяться при каждой правке');

// Воронка видна в отчёте.
ок('воронка выводится в отчёт',
   /function воронкаИсточников\(в\)/.test(SRC) && /ссылок в выдаче/.test(SRC)
   && /замерено нами — сняты числа/.test(SRC),
   'человек снова увидит «130 страниц» без объяснения');
// Её место — в блоке «Источники», а не наверху отчёта (владелица 18.09).
ок('воронка стоит внутри блока источников',
   /<div class="srcbody">'\s*\n?\s*\+ воронкаИсточников/.test(SRC),
   'воронка снова лезет вперёд данных');
ок('в заголовке блока видно, из скольких отобрано',
   /' · отобрано из ' \+ в\.ссылокВыдачи/.test(SRC),
   'вопрос «а сколько вы вообще смотрели» останется без ответа');
ок('сказано, что замер не тратит поисковых запросов',
   /поисковых запросов не тратит/.test(SRC),
   'непонятно, почему замер сотен каналов ничего не стоит');

// Форматы считаются по ВСЕМ замерам, а не по выборке модели: 18.09 замерили
// девятнадцать каналов, а в сводку попали три — «два из трёх, один из трёх».
ок('сводка форматов строится на замерах',
   /const изЗамеров = \(д\.каналыЗамеренные \|\| \[\]\)\.map/.test(SRC)
   && /const записи = изЗамеров/.test(SRC),
   'в форматы снова попадёт только то, что модель выписала');
ок('замеры доезжают до данных модуля',
   /каналыЗамеренные: замеренныеКаналы \}/.test(SRC),
   'разметке нечего считать');
ок('размер из замера идёт в форматы',
   /знаков: к\.длина \|\| null, секунд: к\.секунды \|\| null/.test(SRC),
   'каналы попадут в «размер не известен», хотя мы его замерили');

// Подборка «Топ-50 каналов» — это пятьдесят каналов на одной странице, а мы
// считали её одним источником (владелица 18.09: «блогеров тысячи, а мы
// оцениваем по девятнадцати каналам»).
ок('адреса каналов берутся из текста страниц',
   /function каналыИзТекста\(текст\)/.test(SRC)
   && /const всеИсточники = \(выдержки \|\| \[\]\)\.concat\(изТекста\)/.test(SRC),
   'подборки каналов остаются одним источником вместо пятидесяти');
ок('служебные адреса площадок отсеиваются',
   /t\\\.me\\\/\(\?:share\|joinchat\|proxy/.test(SRC),
   'в замер пойдут ссылки «поделиться» и прокси');
ок('один канал считается один раз, а не по каждому посту',
   /return ч\.slice\(0, 2\)\.join\('\/'\)/.test(SRC),
   'десять постов одного канала дадут десять замеров');
ок('видно, сколько ссылок дал текст страниц',
   /ссылок на каналы в текстах страниц/.test(SRC),
   'непонятно, откуда взялись каналы');

// Отсев мусора ПЕРЕД замером: тайский спам с охватом 94 000, ролик про скам,
// служебные «Join Group Chat» и каналы самого конкурента возглавляли рейтинг
// форматов (18.09).
ок('есть отсев мусорных каналов',
   /function мусорныйКанал\(url, заголовок, конкуренты\)/.test(SRC)
   && /if \(мусорныйКанал\(u, э && э\.title, конкуренты\)\) continue/.test(SRC),
   'в замер снова пойдёт что попало');
ок('каналы конкурентов не замеряем',
   /Канал самого конкурента: там сидят его клиенты/.test(SRC),
   'конкурент попадёт в «кого читает наша аудитория»');
ок('служебные страницы площадок отсеяны',
   /join group chat\|view @/i.test(SRC), 'превью Telegram станут источниками');
ок('чужой язык отсеян',
   /свои \/ буквы < 0\.67/.test(SRC), 'иноязычный спам снова возглавит сводку');
ок('отдельная публикация — не источник',
   /youtube\\\.com\\\/\(\?:watch\|shorts\)/.test(SRC),
   'один ролик будет считаться площадкой');

// Главный рычаг против «двадцати каналов»: подборки. Одна страница «Топ-50»
// даёт полсотни адресов, но выдержка обрезана до 600 знаков — в них помещалась
// одна ссылка. Такие страницы дочитываем целиком (18.09).
ок('подборки ищутся прицельно',
   /const подборочные = \[/.test(SRC) && /топ телеграм каналов для/.test(SRC),
   'подборки будут попадаться случайно');
ок('подборки дочитываются целиком',
   /const подборки = \(выдержки \|\| \[\]\)\.filter\(похожеНаПодборку\)/.test(SRC)
   && /for \(const у of каналыИзТекста\(html\)\)/.test(SRC),
   'из подборки возьмём одну ссылку вместо пятидесяти');
ок('дочитывание подборок ограничено',
   /срокПодборок/.test(SRC) && /\.slice\(0, 25\)/.test(SRC),
   'дочитывание растянет прогон');
ок('видно, сколько подборок дочитано',
   /подборокДочитано: подборки\.length/.test(SRC), 'непонятно, сработал ли приём');

console.log(провалов?('ПРОВАЛОВ: '+провалов):'  воронка источников и отбор замером на месте');
if(провалов) $.NSException.exceptionWithNameReasonUserInfo($('tests'),$('funnel'),$()).raise;
