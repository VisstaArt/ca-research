ObjC.import('Foundation');
// Модуль «Аудитория» разбирается ТРЕМЯ проходами вместо одного вызова.
// 18.09 владелица: «или мы в модуль слишком много блоков вставляем, что ей
// сложно это углублять — она распыляется: там чуть-чуть, тут чуть-чуть».
// Диагноз верный: один вызов заполнял четыре раздела и давал шесть источников
// на весь модуль.
function readFile(p){return $.NSString.stringWithContentsOfFileEncodingError($(p),$.NSUTF8StringEncoding,null).js;}
var ROOT=$.NSFileManager.defaultManager.currentDirectoryPath.js;
var SRC=readFile(ROOT+'/app.jsx');
console.log('tests/m4a-passes.test.js');
var провалов=0;
function ок(имя,усл,что){ if(усл) console.log('  ok   '+имя); else { провалов++; console.log('  FAIL '+имя+(что?': '+что:'')); } }

ок('есть разбор по проходам',
   /async function строгоеM4AПоПроходам\(о\)/.test(SRC), 'нет функции проходов');
ок('модуль зовёт именно его',
   /if \(mod\.id === 'M4A'\) \{\s*\n\s*строгое = await строгоеM4AПоПроходам\(/.test(SRC),
   'M4A снова идёт одним вызовом');

// Подсхемы строятся из общей, чтобы поля не разошлись.
['СХЕМА_M4A_МЕСТА','СХЕМА_M4A_ГОЛОСА','СХЕМА_M4A_ЛИДЕРЫ','СХЕМА_M4A_ИТОГ'].forEach(function(имя){
  ок('есть подсхема ' + имя, new RegExp('const ' + имя + '\\s+= подсхемаM4A').test(SRC),
     'подсхема потерялась');
});
ок('подсхемы берут поля из общей схемы',
   /о\[п\] = СХЕМА_M4A\.properties\[п\]/.test(SRC),
   'поля подсхем разойдутся с основной');

// У каждого прохода СВОЙ срез материала — в этом половина смысла.
ок('материал делится на срезы',
   /const местаСрез = все\.filter\(площадка\)/.test(SRC)
   && /const голосаСрез = все\.filter\(проКонкурента\)/.test(SRC),
   'проходы снова получают весь материал — шум вернётся');
// Деление начисто дало ноль замеров: каналы уходили в «места», а «кого читают»
// оставался с сайтами, у которых счётчиков нет (18.09).
ок('лидерам достаются и площадки',
   /const лидерыСрез = все\.filter\(э => !проКонкурента\(э\)\)/.test(SRC),
   'каналы снова уйдут только в места, и замерять будет нечего');
ок('модели сказано брать каналы в первую очередь',
   /СРЕДИ СТРАНИЦ НИЖЕ ЕСТЬ КАНАЛЫ И ГРУППЫ — берись за них в первую очередь/.test(SRC),
   'модель возьмёт сайты, которые нельзя замерить');
ок('у каждого прохода одна задача',
   (SRC.match(/ЗАДАЧА ЭТОГО ПРОХОДА ОДНА/g)||[]).length === 3,
   'задачи размыты');

// Номера источников должны быть сквозными, иначе ссылки [n] в разных разделах
// указывают на разные страницы.
ок('нумерация источников сквозная',
   /function выдержкиСНомерами\(все, срез\)/.test(SRC)
   && /const номер = new Map\(\(все \|\| \[\]\)\.map\(\(э, i\) => \[э\.url, i \+ 1\]\)\)/.test(SRC),
   'ссылки [n] будут врать');
ок('источники собираются кодом, а не моделью',
   /источники: все\.map\(\(э, i\) => \(\{ номер: i \+ 1/.test(SRC),
   'модель перепишет номера по-своему');

// Итог пишется ПОСЛЕ, на готовых разделах.
ок('итог опирается на найденное',
   /ЧТО НАШЛОСЬ В ЭТОМ МОДУЛЕ/.test(SRC)
   && /Опирайся\s*'\s*\n?\s*\+ 'ТОЛЬКО на перечисленное выше/.test(SRC),
   'итог снова выдумывается');
ок('сбой одного прохода не роняет модуль',
   /catch \(e\) \{\s*\n\s*if \(window\.console\) console\.warn\('Проход ' \+ имя/.test(SRC),
   'один неудачный проход обнулит весь модуль');

// В «кого читает» попал канал, обучающий работе с конструктором конкурента:
// его читают пользователи ТОГО продукта, а не наша аудитория (владелица 18.09 —
// «это вообще не то, что нужно»).
ок('источник проверяется на принадлежность нашей аудитории',
   /ГЛАВНАЯ ПРОВЕРКА, И ОНА ВАЖНЕЕ ВСЕГО ОСТАЛЬНОГО: читает ли этот источник/.test(SRC),
   'в лидеры снова попадут чужие аудитории');
ок('каналы про чужой продукт исключены',
   /каналы и блоги ПРО ЧУЖОЙ ПРОДУКТ/.test(SRC)
   && /Их читают пользователи того продукта/.test(SRC),
   'обучение по конструктору конкурента снова станет «кого читает аудитория»');
ок('широкие площадки без отраслевой привязки исключены',
   /он тоже предприниматель», связи нет/.test(SRC),
   'деловые издания общего профиля заполнят раздел');
ок('требуется назвать, что приводит туда нашего человека',
   /назови, ЧТО ИМЕННО из портрета выше/.test(SRC),
   'связь с аудиторией останется на словах');

// Канал-вещалка с тремястами тысячами подписчиков — не место разговора, а
// канал самого конкурента тем более (18.09).
ок('место отделено от канала-вещалки',
   /СНАЧАЛА ОТДЕЛИ МЕСТО ОТ КАНАЛА/.test(SRC)
   && /канал или сообщество САМОГО КОНКУРЕНТА сюда не пиши никогда/i.test(SRC),
   'в места снова попадут новостные каналы и канал конкурента');
// Блок «через кого узнают» схлопнулся до одной строки: модель отбирала лучшее
// вместо полноты.
ок('в голосах требуется полнота, а не отбор',
   /здесь нужна\s*'\s*\n?\s*\+ 'ПОЛНОТА КАРТЫ, а не отбор лучших/.test(SRC)
   && /одна-две означают/.test(SRC),
   'блок снова схлопнется до пары строк');

console.log(провалов?('ПРОВАЛОВ: '+провалов):'  аудитория разбирается тремя проходами');
if(провалов) $.NSException.exceptionWithNameReasonUserInfo($('tests'),$('m4a-passes'),$()).raise;
