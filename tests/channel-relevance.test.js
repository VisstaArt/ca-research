ObjC.import('Foundation');
// Канал должен быть ПРО НИШУ, а не просто найден в подборке.
// 19.09 дочитывание подборок принесло сотню каналов без разбора: в топ попали
// t.me/yumaks, vk.com/skillfactoryschool, «Клиника Красивые люди Сыктывкар» и
// официальное сообщество Пикабу на два миллиона подписчиков.
function readFile(p){return $.NSString.stringWithContentsOfFileEncodingError($(p),$.NSUTF8StringEncoding,null).js;}
var ROOT=$.NSFileManager.defaultManager.currentDirectoryPath.js;
var SRC=readFile(ROOT+'/app.jsx');
console.log('tests/channel-relevance.test.js');
var провалов=0;
function ок(имя,усл,что){ if(усл) console.log('  ok   '+имя); else { провалов++; console.log('  FAIL '+имя+(что?': '+что:'')); } }
function взять(и){var k=SRC.indexOf('function '+и+'('); var e=SRC.indexOf('\n}\n',k); return SRC.slice(k,e+2);}
eval(взять('словаНиши')); eval(взять('совпаденийСНишей'));
var ОХВАТ_ГИГАНТА=200000; eval(взять('каналПроНишу'));

// Слова берём ИЗ ПОРТРЕТОВ, а не выдумываем.
var портреты=[{сегмент:'Владельцы интернет-магазинов',роль:'собственник',
  интересы:['маркетплейсы Ozon и Wildberries','логистика и фулфилмент','CRM и повторные продажи'],
  что_читают:['Telegram-каналы про e-commerce','кейсы интернет-магазинов']}];
var слова=словаНиши({selectedNiche:'интернет-магазины',audience:'владельцы интернет-магазинов'},портреты,[]);
ок('слова ниши собраны из портретов: '+слова.length, слова.length >= 10, 'слов мало, фильтр не сработает');

[[{title:'Клуб владельцев интернет-магазинов',описание:'сообщество владельцев магазинов'},true,'профильное сообщество'],
 [{title:'Антон Гладченко',описание:'контекстная реклама для интернет-магазинов'},true,'эксперт ниши'],
 [{title:'Пикабу',описание:'Официальное сообщество Пикабу. Истории, юмор, новости'},false,'двухмиллионный паблик не по теме'],
 [{title:'SkillFactory',описание:'Онлайн-школа программирования и анализа данных'},false,'школа программирования'],
 [{title:'Клиника Красивые люди Сыктывкар',описание:'косметология, запись на приём'},false,'чужой бизнес из подборки'],
].forEach(function(п){
  ок(п[2], каналПроНишу(п[0],слова) === п[1],
     (п[1]?'должен пройти':'должен отсеяться')+', а вышло наоборот');
});

// Без описания не отсекаем: сомнение в пользу канала, иначе потеряем закрытые.
ок('канал без описания не отсекается', каналПроНишу({title:'',описание:''},слова) === true,
   'закрытые площадки без og-тегов пропадут все разом');
ок('без слов ниши фильтр молчит', каналПроНишу({title:'что угодно'},[]) === true,
   'при пустых портретах отсеется вообще всё');

// Отсев считается и показывается.
ок('отсев идёт ПОСЛЕ замера',
   /const подходят = готово\.filter\(к => каналПроНишу\(к, слова\)\)/.test(SRC),
   'отсеем до замера — не узнаем, сколько нашли');
ок('отсев виден в воронке',
   /отсеяноПоТеме: отсеяно/.test(SRC) && /не подошли по теме ниши/.test(SRC),
   'человек не увидит, сколько каналов выброшено');
// Имя канала — со страницы, а не голый адрес.
ок('замер снимает имя и описание канала',
   /итог\.имя = \(html\.match\(\/property=\["'\]og:title/.test(SRC)
   && /итог\.описание = /.test(SRC),
   'в отчёте останутся адреса вместо названий');
ок('имя подставляется в замеренный канал',
   /title: з\.имя \|\| э\.title \|\| ''/.test(SRC), 'имя снято, но не доехало');

// Канал из подборки обязан подтвердить нишу: прицельные запросы «топ телеграм-
// каналов» приводят списки самых популярных каналов СТРАНЫ (19.09 — Mash,
// Readovka, TGStat, ВКонтакте с 2,3 млн).
ок('канал из подборки без описания не проходит',
   каналПроНишу({title:'Mash',описание:'',изПодборки:true}, слова) === false,
   'общенациональные медиа снова возглавят рейтинг ниши');
ок('канал из основного поиска без описания проходит',
   каналПроНишу({title:'Какой-то канал',описание:''}, слова) === true,
   'потеряем закрытые площадки, найденные по делу');
ок('пометка о подборке доезжает до замера',
   /изПодборки: !!э\.изПодборки/.test(SRC) && /изПодборки: true/.test(SRC),
   'фильтр не отличит подборочный канал от найденного по делу');
// ОТБОР ЧИСЛОМ, а не правилами словами. Третий заход на словесный баланс снова
// пропустил мусор (19.09: Mash, Readovka, ВКонтакте с 2,3 млн в топ-20), поэтому
// совпадение с нишей теперь считается числом и решает ПОРЯДОК, а не только «да/нет».
ок('совпадения с нишей считаются числом',
   совпаденийСНишей({title:'Клуб владельцев интернет-магазинов',
     описание:'маркетплейсы, логистика, повторные продажи'}, слова) >= 2,
   'профильный канал должен набрать больше одного совпадения');
ок('у чужого канала совпадений нет',
   совпаденийСНишей({title:'Mash',описание:'новости и происшествия'}, слова) === 0,
   'общенациональное медиа не должно набирать очки ниши');
ок('гигант без совпадения отсекается всегда',
   каналПроНишу({title:'ВКонтакте',описание:'Официальное сообщество',
     охватЧислом:2295175}, слова) === false,
   'двухмиллионный паблик снова возглавит рейтинг ниши');
ок('небольшой канал с описанием не по теме тоже отсекается',
   каналПроНишу({title:'Турагентство',описание:'туры и отдых',охватЧислом:900}, слова) === false,
   'описание есть, ниша чужая — не наш');
ок('порядок: сначала совпадение, потом охват',
   /б\.совпадений > 0 \? 1 : 0\) - \(а\.совпадений > 0 \? 1 : 0\)/.test(SRC),
   'наверху снова окажется самый крупный, а не самый подходящий');

// Пустой раздел «кого читает» — тоже ошибка: 19.09 он приехал пустым при ста
// девяноста замеренных каналах.
ок('модели сказано, что пустой раздел — ошибка',
   /НО ПУСТОЙ РАЗДЕЛ — ТОЖЕ ОШИБКА/.test(SRC)
   && /они уже отобраны, и /.test(SRC),
   'раздел снова окажется пустым при полном списке каналов');

console.log(провалов?('ПРОВАЛОВ: '+провалов):'  каналы проверяются на принадлежность нише');
if(провалов) $.NSException.exceptionWithNameReasonUserInfo($('tests'),$('relevance'),$()).raise;
