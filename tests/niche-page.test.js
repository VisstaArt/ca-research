ObjC.import('Foundation');
// Главная страница ниши: верхний уровень — ниши, внутри сводка по всему
// исследованию. Решение владелицы 18.09: «открываешь нишу — видишь общую
// картину, которую можно быстро оценить глазами, а подробности по модулю
// открываешь отдельно».
function readFile(p){return $.NSString.stringWithContentsOfFileEncodingError($(p),$.NSUTF8StringEncoding,null).js;}
var ROOT=$.NSFileManager.defaultManager.currentDirectoryPath.js;
var SRC=readFile(ROOT+'/app.jsx');
console.log('tests/niche-page.test.js');
var провалов=0;
function ок(имя,усл,что){ if(усл) console.log('  ok   '+имя); else { провалов++; console.log('  FAIL '+имя+(что?': '+что:'')); } }

ок('есть дашборд ниши', /function дашбордНиши\(результаты, ниша\)/.test(SRC), 'нет функции');
// Не список строк, а картина: крупные числа и полосы (владелица 18.09).
ок('есть крупные числа', /const плитки = \[\];/.test(SRC), 'дашборд снова стал списком');
ок('есть полосы', /const графики = \[\];/.test(SRC) && /Что заходит у лидеров ниши/.test(SRC),
   'нет графиков');
ок('мера полосы как в отчёте',
   /height:14,background:'var\(--line-2\)'/.test(SRC) && /gap:13/.test(SRC),
   'полосы нарисованы своей мерой');
ок('картина берёт СТРОГИЕ данные, а не текст',
   /if \(r\.строгое\) по\[r\.id\] = r\.строгое/.test(SRC),
   'сводка будет пересказывать текст модуля вместо фактов');
// В картине должны быть разрезы всех ключевых модулей.
['конкурентов разобрано','площадок в работу','каналов аудитории замерено',
 'живых цитат','персон покупателя','офферов готово'].forEach(function(п){
  ок('в плитках есть «'+п+'»', SRC.indexOf(п) > 0, 'модуль не попал в картину');
});
ок('ниши — верхний уровень списка',
   /workNiches\.map\(н => \{/.test(SRC) && /дашбордНиши\(proj\?\.results \|\| \[\], н\)/.test(SRC),
   'ниши снова перемешаны с модулями');
ок('ниша сворачивается',
   /const \[развёрнутаяНиша, setРазвёрнутаяНиша\]/.test(SRC),
   'все ниши будут раскрыты сразу');
ок('пустая картина объяснена',
   /картина появится после прогона/.test(SRC),
   'человек увидит пустоту без объяснения');
ок('сказано, где искать подробности',
   /Подробности — в карточках модулей ниже/.test(SRC),
   'непонятно, куда идти за деталями');
// Русские имена без диакритики: иначе переменная молча не совпадёт.
ок('в коде нет ударений в именах',
   SRC.indexOf('́') < 0, 'символ ударения ломает совпадение имён');

console.log(провалов?('ПРОВАЛОВ: '+провалов):'  главная страница ниши на месте');
if(провалов) $.NSException.exceptionWithNameReasonUserInfo($('tests'),$('niche-page'),$()).raise;
