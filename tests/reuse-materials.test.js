ObjC.import('Foundation');
// Повторный разбор БЕЗ поиска — для всех модулей, а не только для радара.
// 18.09 у владелицы осталось 505 поисковых кредитов, а правок впереди много.
// Каждая правка промпта означала полный новый сбор, хотя страницы те же.
function readFile(p){return $.NSString.stringWithContentsOfFileEncodingError($(p),$.NSUTF8StringEncoding,null).js;}
var ROOT=$.NSFileManager.defaultManager.currentDirectoryPath.js;
var SRC=readFile(ROOT+'/app.jsx');
console.log('tests/reuse-materials.test.js');
var провалов=0;
function ок(имя,усл,что){ if(усл) console.log('  ok   '+имя); else { провалов++; console.log('  FAIL '+имя+(что?': '+что:'')); } }

ок('есть общая подстановка сохранённых выдержек',
   /const сохранённыеВыдержки = /.test(SRC), 'механизм снова только у радара');
// Каждый ищущий модуль обязан спрашивать сохранённое ПЕРЕД поиском.
[['gatherNicheEvidence','разведка ниш'],
 ['gatherCompetitorEvidence','конкуренты'],
 ['gatherContentRadarEvidence','контент-радар'],
 ['gatherAudienceEvidence','аудитория'],
 ['gatherVoCEvidence','голос клиента'],
 ['gatherSeoEvidence','SEO']].forEach(function(п){
  var re=new RegExp('сохранённыеВыдержки\\\\s*\\\\n?\\\\s*\\\\|\\\\|\\\\s*await '+п[0]);
  ок('повтор без поиска: '+п[1], re.test(SRC), 'модуль всегда ищет заново');
});

// Выдержки должны храниться С ТЕКСТОМ, иначе повторный разбор идёт вслепую.
ок('выдержки сохраняются с текстом',
   /content: String\(в\.content \|\| ''\)\.slice\(0, 600\)/.test(SRC),
   'в материалы снова кладутся одни адреса — разбор будет хуже первого');
ок('материалы сохраняются не только у радара',
   /const материалы = \(выдержкиДляХранения\.length/.test(SRC),
   'у остальных модулей повторять будет нечего');
ок('портреты и частотность тоже переиспользуются',
   /портреты = сохранённыеМатериалы\.портреты/.test(SRC)
   && /интересыЗамер = сохранённыеМатериалы\.интересыЗамер \|\| \[\]/.test(SRC),
   'аудитория заново заплатит за частотность');
ок('в отчёте видно, что сбор взят из сохранённого',
   (SRC.match(/Материалы взяты из прошлого сбора/g)||[]).length >= 2,
   'человек не поймёт, что числа не свежие');
ок('кнопка повтора у любого модуля с материалами',
   /\{r\.материалы && \(/.test(SRC), 'кнопка снова привязана к одному модулю');

console.log(провалов?('ПРОВАЛОВ: '+провалов):'  повторный разбор доступен всем модулям');
if(провалов) $.NSException.exceptionWithNameReasonUserInfo($('tests'),$('reuse'),$()).raise;
