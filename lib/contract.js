          // Кого читает аудитория (M4 BLOCK 24E): не продавцы, а те, к кому
          // аудитория ходит за мнением. Добавлено 17.09.
          AUDIENCE_VOICES: pickTable(modulesForNiche, 'M4', 'BLOCK 24E'),
