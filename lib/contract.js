          DISCOVERY_PATHS: pickTable(modulesForNiche, 'M4', 'BLOCK 24G'),
          AUDIENCE_INTERESTS: pickTable(modulesForNiche, 'M4', 'BLOCK 24H'),
          // Не входит в контракт генерации, но полезно потребителю как справка:
