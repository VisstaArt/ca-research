        // человека, и раньше она молча выпадала: фильтр требовал https://
        // (владелица 17.09 — «vc.ru записала, а сюда не попадает»).
        socials: String(brief.socials || '').split(/[\s,\n]+/)
          .map(function (x) { return String(x).trim().replace(/[),.;]+$/, ''); })
          .filter(function (x) {
            return /^(https?:\/\/)?[a-z0-9-]+\.[a-z]{2,}\//i.test(x)
                || /^(https?:\/\/)?t\.me\//i.test(x);
          })
          .map(function (x) { return /^https?:\/\//i.test(x) ? x : 'https://' + x; }),
