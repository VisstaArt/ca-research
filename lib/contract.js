  // Почему не includes: в M1.2 блоки идут «BLOCK 04_0 — Источники разведки»,
  // потом «BLOCK 04 — Target Audience Segments». Поиск по подстроке брал первое
  // совпадение, то есть ИСТОЧНИКИ вместо сегментов — контент-машина полгода
  // получала в AUDIENCE_SEGMENTS список площадок с колонками [n]/URL/Дата и
  // подписывала цитаты номерами строк «1», «2», «3». Нашли на их стороне 03.09.
  //
  // Тот же капкан был у BLOCK 19 против 19A, 07 против 07A/07B/07C, 12 против
  // 12B — я тогда залатала одно место точечно вместо того, чтобы починить сам
  // механизм. Теперь после номера блока обязан идти НЕ буквоцифровой символ:
  // «BLOCK 04» больше не совпадёт ни с «BLOCK 04_0», ни с «BLOCK 04_1».
  const pickTable = (modulesObj, modId, needle) => {
    const mod = modulesObj[modId];
    if (!mod) return [];
    const n = String(needle).toLowerCase();
    const keys = Object.keys(mod.tables);
    const exact = keys.find(k => {
      const low = k.toLowerCase();
      const i = low.indexOf(n);
      if (i < 0) return false;
      const after = low.charAt(i + n.length);
      return after === '' || !/[0-9a-z_]/.test(after);
    });
    if (exact) return mod.tables[exact];
    // Запасной путь — прежнее поведение: лучше отдать похожую таблицу, чем
    // пустоту, если модель озаглавила блок не по шаблону.
    const loose = keys.find(k => k.toLowerCase().includes(n));
    return loose ? mod.tables[loose] : [];
  };
